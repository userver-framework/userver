import dataclasses
import os
import pathlib

import jinja2

from chaotic import cpp_format
from chaotic import jinja_env
from chaotic import layout
from chaotic.back.cpp import renderer as cpp_renderer
from chaotic.back.cpp import tagged
from chaotic.back.cpp import types as cpp_types
from chaotic_openapi.back.cpp.client import types

PARENT_DIR = os.path.dirname(__file__)

TEMPLATE_NAMES = [
    'client_fwd.hpp',
    'client.hpp',
    'client.cpp',
    'client_impl.hpp',
    'client_impl.cpp',
    'qos.hpp',
    'component.hpp',
    'component.cpp',
    'requests.hpp',
    'requests.cpp',
    'responses.hpp',
    'responses.cpp',
    'exceptions.hpp',
    'exceptions.cpp',
]

THIS_FILE_IS_AUTOGENERATED = "/* THIS FILE IS AUTOGENERATED, DON'T EDIT! */\n"


@dataclasses.dataclass
class Context:
    generate_path: pathlib.Path
    clang_format_bin: str
    uservices_library_tvm_guard_hack: bool


@dataclasses.dataclass
class CppOutput:
    rel_path: str
    content: str

    @staticmethod
    def save(outputs: list['CppOutput'], prefix: str) -> None:
        for output in outputs:
            path = os.path.join(prefix, output.rel_path)
            content = THIS_FILE_IS_AUTOGENERATED + output.content
            content = content.strip() + '\n'

            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as ofile:
                ofile.write(content)


def cpp_comment(string: str) -> str:
    comment = string.replace('\r', '').strip().replace('\n', '\n/// ')
    if not comment:
        return ''

    # Not using .capitalize() to avoid lowercasing the second sentence.
    return '/// ' + comment[0].upper() + comment[1:]


def make_env() -> jinja2.Environment:
    env = jinja_env.make_env(
        'chaotic-openapi/chaotic_openapi/back/cpp/client',
        os.path.join(PARENT_DIR),
    )
    env.globals['list'] = list
    env.globals['enumerate'] = enumerate
    env.globals['str'] = str
    env.filters['cpp_comment'] = cpp_comment

    return env


JINJA_ENV = make_env()


def template_names(dynamic_config: str) -> list[str]:
    return TEMPLATE_NAMES if dynamic_config else [name for name in TEMPLATE_NAMES if name != 'qos.hpp']


def template_path(include_dir: str, name: str) -> str:
    if name.endswith('.hpp'):
        return f'include/{include_dir}/{name}'
    return f'src/{include_dir}/{name}'


def schema_paths(include_dir: str, schema_files: list[str]) -> list[str]:
    """Paths (without extension) of the types of untagged schema files, relative to the include root."""
    return [f'{include_dir}/{schema_file.rsplit(".", 1)[0]}' for schema_file in schema_files]


def empty_schema_outputs(paths: list[str], produced: set[str]) -> list[CppOutput]:
    """Empty files of the schema files without types, so that the build can declare them unconditionally."""
    output = []
    for path in paths:
        if path in produced:
            continue
        stem = path.rsplit('/', 1)[-1]
        output.extend([
            CppOutput(rel_path=f'include/{path}_fwd.hpp', content='#pragma once\n'),
            CppOutput(rel_path=f'include/{path}.hpp', content=f'#pragma once\n\n#include "{stem}_fwd.hpp"\n'),
            CppOutput(rel_path=f'include/{path}_parsers.ipp', content=''),
            CppOutput(rel_path=f'include/{path}_sax_parsers.hpp', content='#pragma once\n'),
            CppOutput(rel_path=f'src/{path}.cpp', content=f'#include "{path}.hpp"\n'),
        ])
    return output


def output_files(include_dir: str, dynamic_config: str, schema_paths: list[str]) -> list[str]:
    """Files render() generates, relative to the output root, derived without rendering."""
    files = [template_path(include_dir, name) for name in template_names(dynamic_config)]
    for path in schema_paths:
        files.extend(layout.schema_output_files(path))
    return files


def render_tagged_types(
    schemas: dict[str, cpp_types.CppType],
    closure: layout.Closure,
    context: Context,
) -> list[CppOutput]:
    """The types the closure's inputs declare, named or inline, shared by the client and the handlers."""
    output = []
    for cpp_output in tagged.render(schemas, closure, context.clang_format_bin):
        for file in cpp_output.files:
            output.append(
                CppOutput(
                    rel_path=os.path.join(file.subdir, cpp_output.filepath_wo_ext + file.ext),
                    content=file.content,
                ),
            )
    return output


def render(
    spec: types.ClientSpec,
    context: Context,
    schema_files: list[str] | None = None,
) -> list[CppOutput]:
    assert '-' not in spec.cpp_namespace
    env = {
        'spec': spec,
        'namespace': spec.cpp_namespace,
        'name': spec.client_name,
        'config': spec.dynamic_config,
        'qos_config_schema_hash': spec.dynamic_config_schema_hash,
        'base_url': 'http://example.com',  # TODO
        'operations': spec.operations,
        'tvm_hack': context.uservices_library_tvm_guard_hack,
    }

    # client* files
    output = []
    for name in template_names(spec.dynamic_config):
        tpl = JINJA_ENV.get_template(f'templates/{name}.jinja')
        pp = tpl.render(**env)
        pp = cpp_format.format_pp(pp, binary=context.clang_format_bin)
        output.append(CppOutput(rel_path=template_path(spec.include_dir, name), content=pp))

    if spec.closure:
        # The types of tagged documents are generated by --gen types
        return output

    vfilepath_map = {}
    for cpp_type in spec.extract_cpp_types().values():
        assert cpp_type.json_schema
        filepath = cpp_type.json_schema.source_location().filepath
        vfilepath_map[filepath] = 'clients/{}/{}'.format(
            spec.client_name,
            os.path.basename(filepath),
        )

    # C++ types files
    r = cpp_renderer.OneToOneFileRenderer(
        relative_to='',
        vfilepath_to_relfilepath=vfilepath_map,
        clang_format_bin=context.clang_format_bin,
        generate_serializer=True,
        generate_sax_parser=True,
    )
    cpp_outputs = r.render(
        spec.extract_cpp_types(),
        local_pair_header=False,
    )
    produced_stems: set[str] = set()
    for cpp_output in cpp_outputs:
        produced_stems.add(cpp_output.filepath_wo_ext)
        for file in cpp_output.files:
            output.append(
                CppOutput(
                    rel_path=os.path.join(file.subdir, cpp_output.filepath_wo_ext + file.ext),
                    content=file.content,
                ),
            )

    # For every input schema that produced no C++ types, emit empty stub files
    # so that both CMake and ya.make can unconditionally declare the full 5-file
    # set per schema without special-casing type-less schemas.
    if schema_files is not None:
        output.extend(empty_schema_outputs(schema_paths(spec.include_dir, schema_files), produced_stems))

    return output
